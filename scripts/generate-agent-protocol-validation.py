#!/usr/bin/env python3
"""Generate structural validation from required-presence and format schema comments.

Protobuf decoding preserves unknown fields. This boundary checks semantic presence,
recognized executable enum values and scalar formats without projecting through JSON.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCHEMA = ROOT / 'shared/proto/strato/agent/v1/workload.proto'
GENERATED = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'shared/Sources/StratoShared/Generated'
PREFIX = 'Strato_Agent_V1_'

def blocks(source, pattern):
    result = {}
    for match in re.finditer(pattern, source):
        depth, end = 1, match.end()
        while depth:
            depth += (source[end] == '{') - (source[end] == '}')
            end += 1
        result[match[1]] = source[match.end():end - 1]
    return result

schema = SCHEMA.read_text()
messages = blocks(schema, r'\bmessage (\w+)\s*\{')
enums = blocks(schema, r'\benum (\w+)\s*\{')
swift = blocks((GENERATED / 'strato_agent_v1_workload.pb.swift').read_text(),
               r'public (?:nonisolated )?struct Strato_Agent_V1_(\w+)[^{]*\{')
output = ['// Generated by scripts/generate-agent-protocol-validation.py. Do not edit.',
          '// swift-format-ignore-file',
          'import Foundation', 'import SwiftProtobuf', '',
          'private func requireProtocolField(_ valid: Bool) throws {',
          '    guard valid else { throw AgentProtocolDecodeError.invalidField }', '}', '',
          'extension Google_Protobuf_Timestamp {',
          '    func validateProtocol() throws {',
          '        try requireProtocolField((-62_135_596_800...253_402_300_799).contains(seconds)',
          '            && (0..<1_000_000_000).contains(nanos))', '    }', '}', '']
for name in enums:
    output += [f'extension {PREFIX}{name} {{', '    func validateProtocol() throws {',
               '        switch self {',
               '        case .unspecified, .UNRECOGNIZED: throw AgentProtocolDecodeError.invalidField',
               '        default: break', '        }', '    }', '}', '']
for name, body in messages.items():
    props = [(p.strip('`'), t.strip()) for p, t in re.findall(r'public var (`?\w+`?): ([^\n{]+)', swift[name])
             if not p.startswith('has') and p != 'unknownFields']
    code = []
    normalize = []
    oneof = re.search(r'oneof (\w+) \{', body)
    if oneof:
        field = oneof[1]
        code += [f'        switch {field} {{']
        normalize += [f'        switch {field} {{']
        # Generated oneof cases match the associated-message accessors.
        cases = re.findall(r'case (\w+)\(' + PREFIX, swift[name])
        for case in cases:
            code += [f'        case .{case}(let value): try value.validateProtocol()']
            normalize += [f'        case .{case}(var value):',
                          '            try value.normalizeProtocolIdentifiers()',
                          f'            self.{field} = .{case}(value)']
        code += ['        case nil: throw AgentProtocolDecodeError.missingBody', '        }']
        normalize += ['        case nil: break', '        }']
    else:
        fields = re.findall(r'((?:  //[^\n]*\n)*)  (optional |repeated )?([\w.]+|map<[^>]+>) (\w+) = \d+;', body)
        assert len(fields) == len(props), (name, fields, props)
        for (comments, cardinality, field_type, _), (prop, swift_type) in zip(fields, props):
            has = 'hasID' if prop == 'id' else 'has' + prop[0].upper() + prop[1:]
            required = '// Required:' in comments
            if required:
                code += [f'        try requireProtocolField({has})']
            checks = []
            collection = cardinality == 'repeated ' or field_type.startswith('map<')
            value = 'item' if collection else prop
            if field_type in messages or field_type in enums or field_type == 'google.protobuf.Timestamp':
                checks += [f'try {value}.validateProtocol()']
            if '// Format: uuid.' in comments:
                if swift_type.endswith('Section'):
                    checks += [f'for item in {prop}.values {{ try requireProtocolField(UUID(uuidString: item) != nil) }}']
                else:
                    checks += [f'try requireProtocolField(UUID(uuidString: {value}) != nil)']
            if field_type in messages:
                if cardinality == 'repeated ':
                    normalize += [f'        for index in {prop}.indices {{ try {prop}[index].normalizeProtocolIdentifiers() }}']
                elif field_type.startswith('map<'):
                    raise AssertionError('Message maps need explicit canonicalization support')
                else:
                    normalize += [f'        if {has} {{ try {prop}.normalizeProtocolIdentifiers() }}']
            if '// Format: uuid.' in comments:
                if swift_type.endswith('Section'):
                    normalize += [f'        if {has} {{ {prop}.values = try {prop}.values.map {{ try UUID(protocolString: $0).uuidString }} }}']
                elif collection:
                    normalize += [f'        {prop} = try {prop}.map {{ try UUID(protocolString: $0).uuidString }}']
                else:
                    normalize += [f'        if {has} {{ {prop} = try UUID(protocolString: {prop}).uuidString }}']
            if '// Format: device-name.' in comments:
                checks += [f'try requireProtocolField(VolumeDeviceName.isValid({value}))']
            if '// Format: uint16.' in comments:
                checks += [f'try requireProtocolField({value} <= UInt16.max)']
            if checks:
                joined = '; '.join(checks)
                if collection:
                    code += [f'        for item in {prop} {{ {joined} }}']
                elif not required:
                    code += [f'        if {has} {{ {joined} }}']
                else:
                    code += [f'        {check}' for check in checks]
    if name == 'GuestConfig': code += ['        try validate()']
    output += [f'extension {PREFIX}{name} {{', '    public func validateProtocol() throws {', *code, '    }',
               '    /// Canonical UUID spelling preserves the identity semantics of the historical UUID models.',
               '    public mutating func normalizeProtocolIdentifiers() throws {', *normalize, '    }', '}', '']
(GENERATED / 'AgentProtocolValidation.swift').write_text('\n'.join(output))
